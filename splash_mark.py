def _bit(x, y):
    i = y * W + x
    return (BITS[i >> 3] & (0x80 >> (i & 7))) != 0


def white_count():
    n = 0
    y = 0
    while y < H:
        x = 0
        while x < W:
            if _bit(x, y):
                n += 1
            x += 1
        y += 1
    return n


def show(lcd):
    """Paint the full panel. Returns True when a driver call accepted it.

    Strips of 8 rows keep the expand buffer at 2 KB. The mark includes
    its own black, so this does not clear the panel first.
    """
    if lcd is None:
        return False
    strip = 8
    buf = bytearray(W * strip * 2)
    y = 0
    while y < H:
        n = strip
        if y + n > H:
            n = H - y
        i = 0
        dy = 0
        while dy < n:
            src_y = (y + dy) - DRAW_Y
            src = src_y * _ROW
            dx = 0
            while dx < _ROW:
                if src_y < 0 or src_y >= H:
                    bits = 0
                else:
                    bits = BITS[src + dx]
                b = 0
                while b < 8:
                    if bits & (0x80 >> b):
                        buf[i] = 0xFF
                        buf[i + 1] = 0xFF
                    else:
                        buf[i] = 0
                        buf[i + 1] = 0
                    i += 2
                    b += 1
                dx += 1
            dy += 1
        pushed = False
        raw = getattr(lcd, "drawRawBuf", None)
        if raw is not None:
            try:
                raw(buf, 0, y, W, n, W * n, True)
                pushed = True
            except Exception:
                pushed = False
        if not pushed:
            image = getattr(lcd, "pushImage", None)
            if image is not None:
                try:
                    image(0, y, W, n, buf)
                    pushed = True
                except Exception:
                    pushed = False
        if not pushed:
            return False
        y += n
    return True
